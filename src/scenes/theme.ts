// --- Crisp rendering on high-DPI / scaled-up screens ----------------------
//
// Every scene lays itself out in a fixed 1280x720 coordinate space. If the
// canvas were also 1280x720 pixels, Scale.FIT would stretch it up to fill the
// window -- and on a Retina/HiDPI screen (devicePixelRatio 2+) that stretch
// is what made text and icons look blurry. Instead the canvas is created
// RENDER_SCALE times bigger and each scene's camera is zoomed by the same
// factor (useRenderScale below), so all the layout code keeps using 1280x720
// coordinates while the actual pixels match the screen.

export const GAME_WIDTH = 1280;
export const GAME_HEIGHT = 720;

function computeRenderScale(): number {
  const dpr = window.devicePixelRatio || 1;
  // How much Scale.FIT will enlarge the 960x760 layout to fill the window.
  const fitRatio = Math.max(1, Math.min(window.innerWidth / GAME_WIDTH, window.innerHeight / GAME_HEIGHT));
  // Capped at 3: beyond that the extra pixels aren't visible but cost memory.
  return Phaser.Math.Clamp(Math.ceil(dpr * fitRatio), 1, 3);
}

export const RENDER_SCALE = computeRenderScale();

// Call first thing in every scene's create(): zooms the camera so the
// 1280x720 layout fills the RENDER_SCALE-sized canvas, anchored top-left.
export function useRenderScale(scene: Phaser.Scene): void {
  scene.cameras.main.setOrigin(0, 0).setZoom(RENDER_SCALE);
}

// --- Scene backgrounds ------------------------------------------------------
//
// Full-screen illustrations from public/backgrounds/ (generated by
// scripts/backgrounds.js). Rasterized at up to 2x the layout size so they
// stay sharp when the camera is zoomed; if one fails to load, the scene just
// keeps its plain background color.

export interface BackgroundDef {
  key: string;
  file: string;
}

export const BACKGROUNDS: { classSelect: BackgroundDef; battle: BackgroundDef } = {
  classSelect: { key: "bg-class-select", file: "class-select.svg" },
  battle: { key: "bg-battle", file: "battle.svg" },
};

// Call from a scene's preload().
export function preloadBackground(scene: Phaser.Scene, bg: BackgroundDef): void {
  if (scene.textures.exists(bg.key)) return;
  const scale = Math.min(RENDER_SCALE, 2);
  scene.load.svg(bg.key, `${import.meta.env.BASE_URL}backgrounds/${bg.file}`, {
    width: GAME_WIDTH * scale,
    height: GAME_HEIGHT * scale,
  });
}

// Call first thing in create(), so everything else draws on top of it.
export function addBackground(scene: Phaser.Scene, bg: BackgroundDef): Phaser.GameObjects.Image | null {
  if (!scene.textures.exists(bg.key)) return null;
  return scene.add.image(0, 0, bg.key).setOrigin(0, 0).setDisplaySize(GAME_WIDTH, GAME_HEIGHT);
}

// The background pushed back behind the UI: blurred, dimmed and
// vignetted, so it reads as atmosphere and the cards and panels on top of it
// stay crisp. Built once per texture into a canvas texture (a cheap
// down/up-sample blur, so it works on every browser and renderer).
export function addSoftBackground(
  scene: Phaser.Scene,
  bg: BackgroundDef,
  { blur = 14, dim = 0.46, vignette = 0.88 }: { blur?: number; dim?: number; vignette?: number } = {}
): Phaser.GameObjects.Image | null {
  if (!scene.textures.exists(bg.key)) return null;
  const key = `${bg.key}-soft`;
  if (!scene.textures.exists(key)) {
    const src = scene.textures.get(bg.key).getSourceImage() as CanvasImageSource & { width: number; height: number };
    const W = src.width;
    const H = src.height;
    const texture = scene.textures.createCanvas(key, W, H);
    if (!texture) return addBackground(scene, bg);
    const ctx = texture.getContext();
    // Blur: shrink by ~blur layout px per sample, then scale back up in two
    // smoothed steps. Drawn slightly oversized so the edges don't go soft.
    const k = Math.max(2, Math.round((blur * W) / GAME_WIDTH));
    const small = document.createElement("canvas");
    small.width = Math.max(1, Math.round(W / k));
    small.height = Math.max(1, Math.round(H / k));
    const sctx = small.getContext("2d") as CanvasRenderingContext2D;
    sctx.imageSmoothingQuality = "high";
    sctx.drawImage(src, 0, 0, small.width, small.height);
    // Grow back in doublings: each bilinear step smooths the last, so the
    // result is a soft blur rather than visible blocks.
    let mid = small;
    while (mid.width * 2 <= W) {
      const next = document.createElement("canvas");
      next.width = mid.width * 2;
      next.height = mid.height * 2;
      const nctx = next.getContext("2d") as CanvasRenderingContext2D;
      nctx.imageSmoothingQuality = "high";
      nctx.drawImage(mid, 0, 0, next.width, next.height);
      mid = next;
    }
    ctx.imageSmoothingQuality = "high";
    const bleed = 0.02;
    ctx.drawImage(mid, -W * bleed, -H * bleed, W * (1 + bleed * 2), H * (1 + bleed * 2));
    // Tone down, a touch cooler than black so it doesn't go muddy.
    ctx.fillStyle = `rgba(6, 7, 10, ${dim})`;
    ctx.fillRect(0, 0, W, H);
    // Vignette: clear in the middle, dark at the edges and corners.
    const v = ctx.createRadialGradient(W / 2, H * 0.52, Math.min(W, H) * 0.22, W / 2, H * 0.52, Math.hypot(W, H) * 0.56);
    v.addColorStop(0, "rgba(4, 5, 7, 0)");
    v.addColorStop(0.55, `rgba(4, 5, 7, ${vignette * 0.35})`);
    v.addColorStop(1, `rgba(4, 5, 7, ${vignette})`);
    ctx.fillStyle = v;
    ctx.fillRect(0, 0, W, H);
    // A darker band under the HUD rows at the top.
    const top = ctx.createLinearGradient(0, 0, 0, H * 0.3);
    top.addColorStop(0, "rgba(4, 5, 7, 0.55)");
    top.addColorStop(1, "rgba(4, 5, 7, 0)");
    ctx.fillStyle = top;
    ctx.fillRect(0, 0, W, H * 0.3);
    texture.refresh();
  }
  return scene.add.image(0, 0, key).setOrigin(0, 0).setDisplaySize(GAME_WIDTH, GAME_HEIGHT);
}

// The lobby's dark glass panel, for the battle board: a soft drop shadow, a
// deep navy body that's a shade lighter at the top, a faint inner highlight
// and a 1px gold hairline (optionally with a faint gold glow). `inset`
// draws a recessed variant (slots, sockets): no shadow, darker, fainter edge.
export interface GlassOptions {
  glow?: boolean;
  inset?: boolean;
  edge?: number; // gold hairline alpha
  fill?: number; // body alpha
}

export function drawGlass(
  g: Phaser.GameObjects.Graphics,
  x: number,
  y: number,
  w: number,
  h: number,
  r: number,
  { glow = false, inset = false, edge, fill }: GlassOptions = {}
): Phaser.GameObjects.Graphics {
  const edgeAlpha = edge ?? (inset ? 0.2 : 0.3);
  if (!inset) {
    for (let i = 1; i <= 4; i++) {
      g.fillStyle(0x000000, 0.09);
      g.fillRoundedRect(x - i * 0.5, y + i * 1.5, w + i, h + i, r + i * 0.5);
    }
  }
  g.fillStyle(inset ? 0x06070b : 0x0b0d14, fill ?? (inset ? 0.62 : 0.93));
  g.fillRoundedRect(x, y, w, h, r);
  if (!inset && h > r * 2 + 4) {
    // Lighter navy at the top, fading out by the middle.
    const sheen = 0x1a1e2c;
    g.fillStyle(sheen, 0.55);
    g.fillRoundedRect(x, y, w, r, { tl: r, tr: r, bl: 0, br: 0 });
    const fadeH = Math.max(0, Math.min(h * 0.55, 90) - r);
    g.fillGradientStyle(sheen, sheen, sheen, sheen, 0.55, 0.55, 0, 0);
    g.fillRect(x, y + r, w, fadeH);
    g.lineStyle(1, 0xffffff, 0.06);
    g.lineBetween(x + r, y + 1.5, x + w - r, y + 1.5);
  }
  if (glow) {
    g.lineStyle(6, GOLD, 0.05);
    g.strokeRoundedRect(x - 2, y - 2, w + 4, h + 4, r + 2);
    g.lineStyle(3, GOLD, 0.08);
    g.strokeRoundedRect(x - 1, y - 1, w + 2, h + 2, r + 1);
  }
  g.lineStyle(1, GOLD, edgeAlpha);
  g.strokeRoundedRect(x + 0.5, y + 0.5, w - 1, h - 1, r);
  return g;
}

// A soft drop shadow for text drawn straight on a background illustration.
export function textShadow<T extends Phaser.GameObjects.Text>(text: T): T {
  return text.setShadow(0, 2, "#000000", 6, false, true) as T;
}

// A filled rounded rectangle, its origin at (0,0) like every other Phaser
// shape, with an interactive hit area covering the same rect -- the click
// target for anything drawn with this (class cards, hand cards, buttons).
export function roundedRect(
  scene: Phaser.Scene,
  w: number,
  h: number,
  color: number,
  radius = 12
): Phaser.GameObjects.Graphics {
  const g = scene.add.graphics();
  g.fillStyle(color, 1);
  g.fillRoundedRect(0, 0, w, h, radius);
  g.setInteractive(new Phaser.Geom.Rectangle(0, 0, w, h), Phaser.Geom.Rectangle.Contains);
  return g;
}

export interface ButtonOptions {
  color: number;
  hoverColor: number;
  onClick: () => void;
}

export interface Button {
  container: Phaser.GameObjects.Container;
  setEnabled: (enabled: boolean) => void;
}

// A rounded-rect button with a centered label and hover/disabled handling.
// Returns { container, setEnabled } -- setEnabled(false) dims it and drops
// its interactivity, matching the CSS `:disabled` cards/buttons this
// replaces.
export function createButton(
  scene: Phaser.Scene,
  x: number,
  y: number,
  w: number,
  h: number,
  text: string,
  { color, hoverColor, onClick }: ButtonOptions
): Button {
  const container = scene.add.container(x, y);

  const bg = scene.add.graphics();
  const draw = (fill: number): void => {
    bg.clear();
    bg.fillStyle(fill, 1);
    bg.fillRoundedRect(0, 0, w, h, 8);
  };
  draw(color);
  bg.setInteractive(new Phaser.Geom.Rectangle(0, 0, w, h), Phaser.Geom.Rectangle.Contains);

  const label = scene.add
    .text(w / 2, h / 2, text, { fontFamily: FONT_FAMILY, fontSize: "14px", color: TEXT.white })
    .setOrigin(0.5);

  container.add([bg, label]);
  container.setData("enabled", true);

  bg.on("pointerover", () => container.getData("enabled") && draw(hoverColor));
  bg.on("pointerout", () => container.getData("enabled") && draw(color));
  bg.on("pointerdown", () => container.getData("enabled") && onClick());

  function setEnabled(enabled: boolean): void {
    container.setData("enabled", enabled);
    container.setAlpha(enabled ? 1 : 0.45);
    draw(color);
    if (enabled) bg.setInteractive(new Phaser.Geom.Rectangle(0, 0, w, h), Phaser.Geom.Rectangle.Contains);
    else bg.disableInteractive();
  }

  return { container, setEnabled };
}

// createButton's round sibling: (x, y) is the center, the hit area is the
// circle, and the label (index 1, same as createButton) can be multi-line.
export function createCircleButton(
  scene: Phaser.Scene,
  x: number,
  y: number,
  r: number,
  text: string,
  { color, hoverColor, onClick }: ButtonOptions
): Button {
  const container = scene.add.container(x, y);

  const bg = scene.add.graphics();
  const draw = (fill: number): void => {
    bg.clear();
    bg.fillStyle(fill, 1);
    bg.fillCircle(0, 0, r);
    bg.lineStyle(2, 0xffffff, 0.25);
    bg.strokeCircle(0, 0, r - 1);
  };
  draw(color);
  const hitArea = (): void => {
    bg.setInteractive(new Phaser.Geom.Circle(0, 0, r), Phaser.Geom.Circle.Contains);
  };
  hitArea();

  const label = scene.add
    .text(0, 0, text, { fontFamily: FONT_FAMILY, fontSize: "15px", fontStyle: "800", color: TEXT.white, align: "center" })
    .setOrigin(0.5);

  container.add([bg, label]);
  container.setData("enabled", true);

  bg.on("pointerover", () => container.getData("enabled") && draw(hoverColor));
  bg.on("pointerout", () => container.getData("enabled") && draw(color));
  bg.on("pointerdown", () => container.getData("enabled") && onClick());

  function setEnabled(enabled: boolean): void {
    container.setData("enabled", enabled);
    container.setAlpha(enabled ? 1 : 0.45);
    draw(color);
    if (enabled) hitArea();
    else bg.disableInteractive();
  }

  return { container, setEnabled };
}
